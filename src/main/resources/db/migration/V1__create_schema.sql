create table company (
    id         bigint generated by default as identity primary key,
    name       varchar(200) not null unique,
    website    varchar(500),
    created_at timestamp with time zone not null
);

create table posting (
    id         bigint generated by default as identity primary key,
    company_id bigint not null references company (id) on delete restrict,
    title      varchar(200) not null,
    location   varchar(200),
    url        varchar(500),
    created_at timestamp with time zone not null
);
create index posting_company_id_idx on posting (company_id);

create table contact (
    id         bigint generated by default as identity primary key,
    company_id bigint not null references company (id) on delete restrict,
    name       varchar(200) not null,
    email      varchar(320),
    role       varchar(200)
);
create index contact_company_id_idx on contact (company_id);

-- At most one application per posting, enforced by the unique constraint.
create table application (
    id         bigint generated by default as identity primary key,
    posting_id bigint not null unique references posting (id) on delete restrict,
    status     varchar(20) not null
        check (status in ('DRAFT', 'APPLIED', 'INTERVIEW', 'OFFER', 'REJECTED', 'WITHDRAWN')),
    notes      text,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    version    bigint not null
);

-- Every status change is kept, so statistics can ask which statuses an application ever reached.
create table status_transition (
    id             bigint generated by default as identity primary key,
    application_id bigint not null references application (id) on delete cascade,
    from_status    varchar(20),
    to_status      varchar(20) not null,
    occurred_at    timestamp with time zone not null
);
create index status_transition_application_id_idx on status_transition (application_id);

create table follow_up (
    id             bigint generated by default as identity primary key,
    application_id bigint not null references application (id) on delete cascade,
    due_date       date not null,
    note           varchar(500) not null,
    done           boolean not null default false
);
create index follow_up_application_id_idx on follow_up (application_id);
